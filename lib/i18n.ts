export type MessageKey = keyof (typeof messages)['de']

export function t(lang: Language, key: MessageKey): string {
  return messages[lang][key]
}

export type BrandingKey = Extract<MessageKey, `branding${string}`>

/** The branding page's strings, for the client-side form. */
export function brandingLabels(lang: Language): Record<BrandingKey, string> {
  return Object.fromEntries(Object.entries(messages[lang]).filter(([key]) => key.startsWith('branding'))) as Record<BrandingKey, string>
}

export function statusLabel(lang: Language, status: FormStatus): string {
  return t(lang, status === 'open' ? 'statusOpen' : status === 'closed' ? 'statusClosed' : 'statusExpired')
}

/** Date and time in the configured time zone, e.g. "28.10.2026, 14:03". */
export function formatDateTime(lang: Language, date: Date): string {
  return new Intl.DateTimeFormat(lang === 'de' ? 'de-DE' : 'en-GB', {
    timeZone: site().timeZone,
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(date)
}

/** Formats an ISO date answer (YYYY-MM-DD) for display. */
export function formatDate(lang: Language, isoDate: string): string {
  const [y, m, d] = isoDate.split('-').map(Number)
  return new Intl.DateTimeFormat(lang === 'de' ? 'de-DE' : 'en-GB', { timeZone: 'UTC', dateStyle: 'medium' }).format(
    new Date(Date.UTC(y, m - 1, d)),
  )
}

/** Count with a singular or plural noun, e.g. "1 Antwort", "3 Antworten". */
export function plural(lang: Language, count: number, one: MessageKey, many: MessageKey): string {
  return `${count} ${t(lang, count === 1 ? one : many)}`
}
